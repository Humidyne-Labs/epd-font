def export_bdf(strike: CompiledStrike, out_path: Path, dpi: float = 188.15) -> Path:
    """Serialize strike to Adobe BDF 2.1 format (SPEC-EPD-FONT-001 Section 6.3.3)."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    dpi_i = round(dpi)
    lines = [
        "STARTFONT 2.1",
        f"COMMENT Generated by epd-font v2.0.0 ({strike.symbol_name})",
        f"FONT -Humidyne-{strike.symbol_name}-R-Normal--{strike.ppem}-{strike.ppem * 10}-{dpi_i}-{dpi_i}-P-0-ISO10646-1",
        f"SIZE {strike.ppem} {dpi_i} {dpi_i}",
        f"FONTBOUNDINGBOX {strike.ppem} {strike.line_height} 0 {-strike.font_descent}",
        "STARTPROPERTIES 4",
        f"FONT_ASCENT {strike.font_ascent}",
        f"FONT_DESCENT {strike.font_descent}",
        f"PIXEL_SIZE {strike.ppem}",
        f"RESOLUTION_Y {dpi_i}",
        "ENDPROPERTIES",
        f"CHARS {len(strike.glyphs)}",
    ]

    for g in strike.glyphs:
        dwidth = g.advance_px
        swidth = round(dwidth * 72000.0 / (max(1, strike.ppem) * max(1, dpi_i)))
        lines.extend([
            f"STARTCHAR U+{g.codepoint:04X}",
            f"ENCODING {g.codepoint}",
            f"SWIDTH {swidth} 0",
            f"DWIDTH {dwidth} 0",
            f"BBX {g.box_w} {g.box_h} {g.ofs_x} {g.ofs_y}",
            "BITMAP",
        ])
        if g.box_w == 0 or g.box_h == 0:
            lines.append("00")
        else:
            row_bytes = (g.box_w + 7) // 8
            for r in range(g.box_h):
                bits = "".join("1" if g.bitmap[r, c] else "0" for c in range(g.box_w)).ljust(row_bytes * 8, "0")
                hex_row = "".join(f"{int(bits[b * 8 : (b + 1) * 8], 2):02X}" for b in range(row_bytes))
                lines.append(hex_row)
        lines.append("ENDCHAR")

    lines.append("ENDFONT")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path


def write_pbm_p1(bitmap: np.ndarray, out_path: Path) -> None:
    """Write ASCII P1 Portable Bitmap (1 = ink, 0 = white)."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    h, w = bitmap.shape if bitmap.size > 0 else (1, 1)
    arr = bitmap if bitmap.size > 0 else np.zeros((1, 1), dtype=np.uint8)
    rows = [" ".join("1" if v else "0" for v in arr[r]) for r in range(h)]
    out_path.write_text(f"P1\n{w} {h}\n" + "\n".join(rows) + "\n", encoding="utf-8")


def write_pbm_p4(bitmap: np.ndarray, out_path: Path) -> None:
    """Write packed binary P4 Portable Bitmap (1 = ink, 0 = white)."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    h, w = bitmap.shape if bitmap.size > 0 else (1, 1)
    arr = (bitmap > 0).astype(np.uint8) if bitmap.size > 0 else np.zeros((1, 1), dtype=np.uint8)
    packed = np.packbits(arr, axis=1, bitorder="big").tobytes()
    header = f"P4\n{w} {h}\n".encode("ascii")
    out_path.write_bytes(header + packed)


def render_text_bitmap(strike: CompiledStrike, text: str, pad_x: int = 2, pad_y: int = 2) -> np.ndarray:
    """Render a string using exact strike glyph bitmaps & advance widths onto a 0/1 array."""
    gmap = {g.codepoint: g for g in strike.glyphs}
    total_w = sum((gmap[ord(ch)].advance_px if ord(ch) in gmap else strike.ppem // 2) for ch in text)
    canvas_w = max(1, total_w + 2 * pad_x)
    canvas_h = max(1, strike.line_height + 2 * pad_y)
    canvas = np.zeros((canvas_h, canvas_w), dtype=np.uint8)

    pen_x = pad_x
    baseline_y = pad_y + strike.font_ascent
    for ch in text:
        g = gmap.get(ord(ch))
        if g is None:
            pen_x += strike.ppem // 2
            continue
        if g.box_w > 0 and g.box_h > 0:
            x0 = pen_x + g.ofs_x
            y0 = baseline_y - (g.ofs_y + g.box_h)
            for r in range(g.box_h):
                yy = y0 + r
                if 0 <= yy < canvas_h:
                    for c in range(g.box_w):
                        xx = x0 + c
                        if 0 <= xx < canvas_w and g.bitmap[r, c]:
                            canvas[yy, xx] = 1
        pen_x += g.advance_px
    return canvas


def _build_lvgl_cmaps(glyphs: list[RasterizedGlyph]) -> list[dict]:
    """Partition sorted glyphs into FORMAT0_TINY and SPARSE_TINY LVGL CMAP subtables."""
    if not glyphs:
        return []
    subtables: list[dict] = []
    i = 0
    n = len(glyphs)
    while i < n:
        j = i
        while j + 1 < n and glyphs[j + 1].codepoint == glyphs[j].codepoint + 1:
            j += 1
        run_len = j - i + 1
        if run_len >= 8:
            subtables.append({
                "type": "LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY",
                "range_start": glyphs[i].codepoint,
                "range_length": run_len,
                "glyph_id_start": glyphs[i].glyph_id,
                "codes": [],
            })
            i = j + 1
        else:
            sparse_codes: list[int] = []
            start_gid = glyphs[i].glyph_id
            start_code = glyphs[i].codepoint
            while i < n:
                k = i
                while k + 1 < n and glyphs[k + 1].codepoint == glyphs[k].codepoint + 1:
                    k += 1
                if (k - i + 1) >= 8 or (glyphs[i].codepoint - start_code > 0xFFFF):
                    break
                sparse_codes.append(glyphs[i].codepoint)
                i += 1
            subtables.append({
                "type": "LV_FONT_FMT_TXT_CMAP_SPARSE_TINY",
                "range_start": start_code,
                "range_length": sparse_codes[-1] - start_code + 1,
                "glyph_id_start": start_gid,
                "codes": sparse_codes,
            })
    return subtables


def export_lvgl_c_file(strike: CompiledStrike, out_path: Path) -> int:
    """Emit LVGL >= 9.6.0 1-bpp C source file and return approximate .rodata footprint."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    sym = strike.symbol_name
    guard = sym.upper()

    bmp_offsets: list[int] = []
    total_bmp = 0
    bmp_lines: list[str] = []
    for g in strike.glyphs:
        bmp_offsets.append(total_bmp)
        packed = g.pack_1bpp_bytes()
        bmp_lines.append(f"    /* U+{g.codepoint:04X} ({g.box_w}x{g.box_h}) */")
        for idx in range(0, len(packed), 12):
            bmp_lines.append("    " + ", ".join(f"0x{b:02x}" for b in packed[idx : idx + 12]) + ",")
        total_bmp += len(packed)
    if total_bmp == 0:
        bmp_lines.append("    0x00")

    lines = [
        f"/* Auto-generated by epd-font v2.0.0 — {sym} ({strike.ppem} px, 1-bpp) */",
        '#ifdef __has_include',
        '    #if __has_include("lvgl.h")',
        '        #include "lvgl.h"',
        "    #else",
        '        #include "lvgl/lvgl.h"',
        "    #endif",
        "#else",
        '    #include "lvgl/lvgl.h"',
        "#endif",
        "",
        f"#ifndef {guard}",
        f"#define {guard} 1",
        "#endif",
        f"#if {guard}",
        "",
        "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {",
        *bmp_lines,
        "};",
        "",
        "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
        "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},",
    ]
    for idx, g in enumerate(strike.glyphs):
        comma = "," if idx + 1 < len(strike.glyphs) else ""
        lines.append(
            f"    {{.bitmap_index = {bmp_offsets[idx]}, .adv_w = {g.adv_w_fp4}, "
            f".box_w = {g.box_w}, .box_h = {g.box_h}, .ofs_x = {g.ofs_x}, .ofs_y = {g.ofs_y}}}{comma}"
        )
    lines.extend(["};", ""])

    cmaps = _build_lvgl_cmaps(strike.glyphs)
    for c_idx, cm in enumerate(cmaps):
        if cm["type"] == "LV_FONT_FMT_TXT_CMAP_SPARSE_TINY":
            offsets = [f"0x{c - cm['range_start']:04x}" for c in cm["codes"]]
            lines.append(f"static const uint16_t unicode_list_{c_idx}[] = {{")
            for k in range(0, len(offsets), 10):
                lines.append("    " + ", ".join(offsets[k : k + 10]) + ",")
            lines.extend(["};", ""])

    if cmaps:
        lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
        for c_idx, cm in enumerate(cmaps):
            comma = "," if c_idx + 1 < len(cmaps) else ""
            u_list = f"unicode_list_{c_idx}" if cm["codes"] else "NULL"
            lines.extend([
                "    {",
                f"        .range_start = {cm['range_start']}, .range_length = {cm['range_length']}, .glyph_id_start = {cm['glyph_id_start']},",
                f"        .unicode_list = {u_list}, .glyph_id_ofs_list = NULL, .list_length = {len(cm['codes'])}, .type = {cm['type']}",
                f"    }}{comma}",
            ])
        lines.extend(["};", ""])

    cmaps_ptr = "cmaps" if cmaps else "NULL"
    lines.extend([
        "static const lv_font_fmt_txt_dsc_t font_dsc = {",
        "    .glyph_bitmap = glyph_bitmap,",
        "    .glyph_dsc = glyph_dsc,",
        f"    .cmaps = {cmaps_ptr},",
        "    .kern_dsc = NULL,",
        "    .kern_scale = 0,",
        f"    .cmap_num = {len(cmaps)},",
        "    .bpp = 1,",
        "    .kern_classes = 0,",
        "    .bitmap_format = 0,",
        "};",
        "",
        f"const lv_font_t {sym} = {{",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        f"    .line_height = {strike.line_height},",
        f"    .base_line = {strike.base_line},",
        "    .subpx = LV_FONT_SUBPX_NONE,",
        "    .underline_position = -1,",
        "    .underline_thickness = 1,",
        "    .dsc = &font_dsc,",
        "    .fallback = NULL,",
        "    .user_data = NULL,",
        "};",
        "",
        f"#endif /* {guard} */",
    ])
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return total_bmp + (len(strike.glyphs) + 1) * 8 + len(cmaps) * 24 + 64


def export_csv_metrics(strike: CompiledStrike, metrics_dir: Path) -> None:
    """Export char_widths_<symbol>.csv and kern_pairs_<symbol>.csv for DuckDB & MCP."""
    metrics_dir.mkdir(parents=True, exist_ok=True)
    w_path = metrics_dir / f"char_widths_{strike.symbol_name}.csv"
    with w_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["unicode_dec", "unicode_hex", "char", "adv_w_raw", "width_px", "box_w", "box_h", "ofs_x", "ofs_y"])
        for g in strike.glyphs:
            ch = chr(g.codepoint) if g.codepoint >= 0x20 else ""
            writer.writerow([g.codepoint, f"0x{g.codepoint:04X}", ch, g.adv_w_fp4, g.advance_px, g.box_w, g.box_h, g.ofs_x, g.ofs_y])

    k_path = metrics_dir / f"kern_pairs_{strike.symbol_name}.csv"
    with k_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["left_unicode", "right_unicode", "kern_px"])


def export_master_headers(strikes: list[CompiledStrike], c_dir: Path) -> None:
    """Emit epd_fonts.h and humid1_fonts.h / h1os_fonts.h declarations."""
    c_dir.mkdir(parents=True, exist_ok=True)
    decls = [f"LV_FONT_DECLARE({s.symbol_name});" for s in sorted(strikes, key=lambda x: x.symbol_name)]
    header_body = "\n".join([
        "#pragma once",
        '#include "lvgl.h"',
        "",
        *decls,
        "",
    ])
    (c_dir / "epd_fonts.h").write_text(header_body, encoding="utf-8")
    (c_dir / "humid1_fonts.h").write_text('#pragma once\n#include "epd_fonts.h"\n', encoding="utf-8")
    (c_dir / "h1os_fonts.h").write_text('#pragma once\n#include "epd_fonts.h"\n', encoding="utf-8")


def export_strike_vault(strikes: list[CompiledStrike], vault_path: Path) -> None:
    """Write humid1_epd_vault.json.gz for epd_typography.py / embedded-ops MCP."""
    vault_path.parent.mkdir(parents=True, exist_ok=True)
    payload: dict[str, object] = {"schema_version": "2.0.0", "strikes": {}}
    strikes_dict: dict[str, dict] = {}
    for s in strikes:
        strikes_dict[s.symbol_name] = {
            "family": s.modifier,
            "style": s.style,
            "size_px": s.ppem,
            "line_height": s.line_height,
            "base_line": s.base_line,
            "source_ttf": s.ttf_path.name,
            "glyphs": [
                {
                    "cp": g.codepoint,
                    "gid": g.glyph_id,
                    "adv_w_fp4": g.adv_w_fp4,
                    "box_w": g.box_w,
                    "box_h": g.box_h,
                    "ofs_x": g.ofs_x,
                    "ofs_y": g.ofs_y,
                    "rows": g.rows,
                }
                for g in s.glyphs
            ],
            "kern_pairs": [],
        }
    payload["strikes"] = strikes_dict
    with gzip.open(vault_path, "wt", encoding="utf-8") as f:
        json.dump(payload, f)
