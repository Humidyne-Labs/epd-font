def run_screen_width_audit(
    strike_cache: Dict[str, Tuple[Dict[int, GlyphStrike], int, int]],
    kern_cache: Dict[str, Dict[Tuple[int, int], int]],
    montserrat_metrics_dir: Optional[Path] = None,
    screen_width: int = 200,
    screen_height: int = 200,
    safe_margin: int = 6,
    dpi: float = 188.15,
    panel_name: str = "Humiditron / humid1 Reference EPD",
    custom_rows: Optional[List[dict]] = None,
) -> List[dict]:
    """Audit horizontal string widths against the target display's usable pixel width budget."""
    mont_widths: Dict[int, Dict[int, float]] = {14: {}, 20: {}}
    if montserrat_metrics_dir and montserrat_metrics_dir.is_dir():
        for sz in (14, 20):
            p = montserrat_metrics_dir / f"char_widths_montserrat_{sz}.csv"
            if p.is_file():
                with p.open("r", encoding="utf-8-sig") as f:
                    for row in csv.DictReader(f):
                        mont_widths[sz][int(row["unicode_dec"])] = float(row["width_px"])

    def measure_mont(text: str, sz: int) -> int:
        if not mont_widths.get(sz):
            return 0
        return int(round(sum(mont_widths[sz].get(ord(c), 8.0) for c in text)))

    usable_budget = max(32, screen_width - (2 * safe_margin))
    x_max = screen_width - safe_margin
    fb_gmap = strike_cache.get("humid1_font_plex_sans_normal_14", strike_cache.get("plex_sans_normal_14", ({}, 0, 0)))[0]
    results = []
    print("\n" + "=" * 106)
    print(
        f"{panel_name.upper()} {screen_width}x{screen_height} ({dpi:.2f} DPI) SCREEN WIDTH AUDIT "
        f"(MAX BUDGET: {usable_budget} px [X={safe_margin}..{x_max}])"
    )
    print("=" * 106)
    print(f"{'Screen / Row':<34} | {'Legacy Mont':>11} | {'Plex Sans':>9} | {'Sans+Mono':>9} | {'Plex Cond':>9} | {'Sans Clr':>8} | {'Status'}")
    print("-" * 106)

    rows_to_run = H1OS_CANONICAL_SCREEN_ROWS
    if custom_rows:
        rows_to_run = [
            (
                r.get("screen", "Screen"),
                r.get("row", "Row"),
                r.get("left", ""),
                r.get("right", ""),
                r.get("left_font", "plex_sans_normal_14"),
                r.get("right_font", "plex_mono_normal_14"),
                int(r.get("min_gap_px", 8)),
            )
            for r in custom_rows
        ]

    for scr_name, row_desc, l_str, r_str, sans_sym, mono_sym, min_gap in rows_to_run:
        if sans_sym not in strike_cache and f"humid1_font_{sans_sym}" in strike_cache:
            sans_sym = f"humid1_font_{sans_sym}"
        if mono_sym not in strike_cache and f"humid1_font_{mono_sym}" in strike_cache:
            mono_sym = f"humid1_font_{mono_sym}"
        s_gmap = strike_cache.get(sans_sym, ({}, 0, 0))[0]
        m_gmap = strike_cache.get(mono_sym, s_gmap if not strike_cache.get(mono_sym) else ({}, 0, 0))
        if isinstance(m_gmap, tuple):
            m_gmap = m_gmap[0]
        s_kmap = kern_cache.get(sans_sym, {})
        m_kmap = kern_cache.get(mono_sym, {})

        l_sans_px = measure_lvgl_string_px(l_str, s_gmap, s_kmap, fb_gmap)
        r_sans_px = measure_lvgl_string_px(r_str, s_gmap, s_kmap, fb_gmap)
        r_mono_px = measure_lvgl_string_px(r_str, m_gmap, m_kmap, fb_gmap)

        total_sans = l_sans_px + r_sans_px
        total_mixed = l_sans_px + r_mono_px

        cond_key = "humid1_font_plex_cond_normal_16" if "humid1_font_plex_cond_normal_16" in strike_cache else "plex_cond_normal_16"
        cond_gmap = strike_cache[cond_key][0] if cond_key in strike_cache else s_gmap
        cond_kmap = kern_cache.get(cond_key, {})
        total_cond = (
            measure_lvgl_string_px(l_str, cond_gmap, cond_kmap, fb_gmap)
            + measure_lvgl_string_px(r_str, cond_gmap, cond_kmap, fb_gmap)
        )

        mont_sz = 20 if "20" in sans_sym else 14
        total_mont = measure_mont(l_str, mont_sz) + measure_mont(r_str, mont_sz)

        clearance = usable_budget - total_sans
        status = "PASS" if clearance >= min_gap else "WARN (TIGHT)"
        label = f"{scr_name.split(':')[0]} - {row_desc[:22]}"
        print(
            f"{label:<34} | {total_mont:>9}px | {total_sans:>7}px | {total_mixed:>7}px | {total_cond:>7}px | {clearance:>+6}px | {status}"
        )
        results.append({
            "screen": scr_name,
            "row": row_desc,
            "left_text": l_str,
            "right_text": r_str,
            "montserrat_px": total_mont,
            "plex_sans_px": total_sans,
            "plex_mixed_px": total_mixed,
            "plex_cond_16_px": total_cond,
            "clearance_px": clearance,
            "status": status,
        })
    print("=" * 106 + "\n")
    return results


def write_total_disk_size_report(
    c_out_dir: Path,
    root_out: Path,
    dist_root: Optional[Path],
    compiled_details: Sequence[dict],
    vault_path: Optional[Path],
    scheme_id: str,
    dpi: float = 188.15,
    scheme_cfg: Optional[dict] = None,
    hw_spec: Optional[TargetHardwareSpec] = None,
    hw_scheme_cli: Optional[str | Path] = None,
    scheme_path: Optional[Path] = None,
) -> Path:
    """
    Generate `total_disk_size.txt` and `rom_space_estimate.txt` alongside the generated `.c`/`.h`
    font assets using strictly validated hardware scheme attributes (`esp32s3-N8R8-hw_scheme.json`
    or `generic_hw.json`) with ZERO hardcoded partition defaults and a single `3 MByte` (`3,145,728` bytes)
    supported partition target.
    """
    if hw_spec is None:
        hw_spec = load_and_validate_hardware_scheme(
            scheme_cfg=scheme_cfg,
            hw_scheme_cli=hw_scheme_cli,
            scheme_path=scheme_path,
        )

    total_rom_b = sum(int(d["rom_b"]) for d in compiled_details)
    total_c_disk_b = 0
    if c_out_dir.is_dir():
        for f in c_out_dir.glob("*.c"):
            total_c_disk_b += f.stat().st_size
        for f in c_out_dir.glob("*.h"):
            total_c_disk_b += f.stat().st_size
    vault_b = vault_path.stat().st_size if (vault_path and vault_path.is_file()) else 0

    part_bytes = hw_spec.partition_1_bytes
    eff_dpi = dpi if dpi is not None else hw_spec.dpi
    rem_bytes = part_bytes - total_rom_b
    util_pct = (total_rom_b * 100.0) / float(part_bytes)
    status_str = "FITS" if rem_bytes >= 0 else "EXCEEDS BUDGET"

    lines = [
        "=" * 120,
        f"HUMIDYNE LABS / HUMIDITRON `epd-font` v{TOOL_VERSION} — APPROXIMATE FLASH ROM (.rodata) & DISK SIZE REPORT",
        "=" * 120,
        "  Project                      : A 1-bit EPD font generator and asset pipeline for embedded displays",
        f"  Scheme ID                    : {scheme_id}",
        f"  Hardware Scheme ID           : {hw_spec.hw_scheme_id} ({hw_spec.hw_scheme_path.name if hw_spec.hw_scheme_path else 'scheme target_display'})",
        f"  Target Chip Name (chip_name) : {hw_spec.chip_name} ({hw_spec.soc_vendor} — {hw_spec.cpu_architecture} @ {hw_spec.cpu_freq_mhz} MHz)",
        f"  Target Memory Architecture   : Flash={hw_spec.flash_total} ({hw_spec.flash_total_bytes:,} B) | PSRAM={hw_spec.psram_total} | SRAM={hw_spec.sram_total}",
        f"  Partition 1 (partition_1)    : {hw_spec.partition_1} ({part_bytes:,} bytes / {part_bytes / 1024.0:.2f} KB / {part_bytes / (1024.0 * 1024.0):.2f} MBytes)",
        f"  Target Display Panel         : {hw_spec.panel} ({hw_spec.controller}, {hw_spec.width_px}x{hw_spec.height_px} px, {hw_spec.color_depth_bpp}-BPP {hw_spec.lvgl_color_format})",
        f"  Target Display DPI           : {eff_dpi:.1f} DPI (1 typographic pt = 1/72 inch = {eff_dpi/72.0:.3f} px @ {eff_dpi:.1f} DPI)",
        f"  Total Compiled Strikes       : {len(compiled_details)} strikes",
        f"  Expected MCU Flash (.rodata) : {total_rom_b:12,d} bytes  ({total_rom_b / 1024.0:8.2f} KB  /  {total_rom_b / (1024.0 * 1024.0):6.3f} MBytes)",
        f"  Host .c + .h Source Disk Size: {total_c_disk_b:12,d} bytes  ({total_c_disk_b / 1024.0:8.2f} KB  /  {total_c_disk_b / (1024.0 * 1024.0):6.3f} MBytes)",
        f"  Compressed Strike Vault Size : {vault_b:12,d} bytes  ({vault_b / 1024.0:8.2f} KB)",
        "=" * 120,
        "",
        f"1. TARGET HARDWARE FLASH PARTITION UTILIZATION ({hw_spec.chip_name} — SINGLE 3 MBYTE PARTITION SPEC)",
        "-" * 120,
        f"  {'Partition Identifier & Label':<44} | {'Budget Bytes':>14} | {'Used (.rodata)':>14} | {'Remaining Free':>16} | {'Utilization':>11} | {'Status'}",
        "-" * 120,
        f"  {f'partition_1 ({hw_spec.partition_1} / {hw_spec.chip_name})':<44} | {part_bytes:>12,d} B | {total_rom_b:>12,d} B | {f'{rem_bytes / 1024.0:+,.1f} KB':>16} | {util_pct:>10.2f}% | {status_str}",
        "-" * 120,
        "",
        "2. APPROXIMATE ROM SPACE PER FONT FILE PAIR (NORMAL + BOLD BY FAMILY AND SIZE VS. 3 MBYTE PARTITION)",
        "-" * 120,
        f"  {'Family':<16} | {'Size':>6} | {'Normal Strike (.rodata)':>26} | {'Bold Strike (.rodata)':>26} | {'Pair Total (Norm+Bold)':>26} | {'% of 3 MByte'}",
        "-" * 120,
    ]

    by_fam_sz: Dict[Tuple[str, int], Dict[str, int]] = {}
    for d in compiled_details:
        key = (str(d["family"]), int(d["sz"]))
        by_fam_sz.setdefault(key, {})[str(d["role"])] = int(d["rom_b"])

    for (fam, sz), role_map in sorted(by_fam_sz.items()):
        norm_b = role_map.get("normal", role_map.get("regular", role_map.get("solid", 0)))
        bold_b = role_map.get("bold", role_map.get("filled", role_map.get("fill", 0)))
        pair_b = norm_b + bold_b
        pct_3mb = (pair_b * 100.0) / float(part_bytes)
        lines.append(
            f"  {fam:<16} | {sz:>4d}px | {norm_b:>13,d} B ({norm_b/1024.0:6.2f} KB) | "
            f"{bold_b:>13,d} B ({bold_b/1024.0:6.2f} KB) | {pair_b:>13,d} B ({pair_b/1024.0:6.2f} KB) | "
            f"{pct_3mb:>10.4f}%"
        )

    lines.extend([
        "",
        "3. SUBTOTALS BY FONT / ICON FAMILY",
        "-" * 120,
        f"  {'Family':<18} | {'Strikes':>7} | {'Total Glyphs':>12} | {'MCU Flash (.rodata)':>22} | {'Host .c Disk Size':>22} | {'% of Build'}",
        "-" * 120,
    ])
    fam_groups: Dict[str, List[dict]] = {}
    for d in compiled_details:
        fam_groups.setdefault(d["family"], []).append(d)
    for fam, items in fam_groups.items():
        f_rom = sum(int(x["rom_b"]) for x in items)
        f_disk = sum(int(x["c_disk_b"]) for x in items)
        f_glyphs = sum(int(x["glyph_count"]) for x in items)
        f_pct = (f_rom * 100.0 / total_rom_b) if total_rom_b > 0 else 0.0
        lines.append(
            f"  {fam:<18} | {len(items):>7d} | {f_glyphs:>12,d} | {f_rom:>10,d} B ({f_rom/1024.0:6.1f} KB) | "
            f"{f_disk:>10,d} B ({f_disk/1024.0:6.1f} KB) | {f_pct:>9.2f}%"
        )

    lines.extend([
        "",
        "4. PER-STRIKE DETAILED FLASH (.rodata) & DISK FOOTPRINT TABLE",
        "-" * 120,
        f"  {'Strike Symbol Name':<36} | {'Em(px)':>6} | {'pt@96':>6} | {'pt@DPI':>6} | {'LineHt':>6} | {'Glyphs':>6} | {'Kern':>5} | {'MCU Flash (.rodata)':>20} | {'Host .c Disk Size':>18}",
        "-" * 120,
    ])
    for d in compiled_details:
        sz = int(d["sz"])
        pt96 = sz * 72.0 / 96.0
        pt_dpi = sz * 72.0 / eff_dpi
        rom_b = int(d["rom_b"])
        c_b = int(d["c_disk_b"])
        lines.append(
            f"  {d['sym_name']:<36} | {sz:>4d}px | {pt96:>4.1f}pt | {pt_dpi:>4.1f}pt | {int(d['line_h']):>4d}px | "
            f"{int(d['glyph_count']):>6,d} | {int(d['kern_count']):>5,d} | {rom_b:>9,d} B ({rom_b/1024.0:6.2f} KB) | {c_b:>8,d} B ({c_b/1024.0:5.1f} KB)"
        )
    lines.append("=" * 120)
    report_text = "\n".join(lines) + "\n"

    out_paths = [
        c_out_dir / "total_disk_size.txt",
        c_out_dir / "rom_space_estimate.txt",
        root_out / "total_disk_size.txt",
        root_out / "rom_space_estimate.txt",
    ]
    if dist_root:
        out_paths.append(dist_root / "total_disk_size.txt")
        out_paths.append(dist_root / "rom_space_estimate.txt")
        if (dist_root / "fonts").is_dir():
            out_paths.append(dist_root / "fonts" / "total_disk_size.txt")
            out_paths.append(dist_root / "fonts" / "rom_space_estimate.txt")

    for p in out_paths:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(report_text, encoding="utf-8")

    return out_paths[0]
